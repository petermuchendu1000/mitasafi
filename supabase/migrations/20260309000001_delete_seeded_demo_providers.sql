--   3. Fake ratings, reviews, response times, job counts
--
-- This migration removes ONLY seeded demo data, preserving:
--   ✅ Real providers (registered through the application)
--   ✅ Discovery layer (service_types, service_categories, subcategories, services)
--   ✅ Neighborhoods, locations, reference data
--
-- Dependencies cascade via ON DELETE CASCADE on:
--   provider_services, provider_service_areas, provider_availability_intervals,
--   provider_documents, provider_verification_documents, provider_reviews,
--   social_link_clicks, saved_providers
